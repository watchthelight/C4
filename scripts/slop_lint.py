#!/usr/bin/env python3
# <wtl> project: c4 | file: scripts/slop_lint.py | author: watchthelight </wtl>
"""Catch AI writing tells and non-ASCII text before they reach the public repo. Exit 1 on any hard hit.

  python scripts/slop_lint.py [PATH ...]           (default: all tracked text files)
  python scripts/slop_lint.py --commit-msg FILE    (git commit-msg hook: subject and trailer rules too)
  python scripts/slop_lint.py --strict [PATH ...]  (warnings fail too)

Hard rules: any non-ASCII character outside fenced code blocks (that covers em and en dashes, unicode
arrows, curly quotes and emoji), the filler phrases in HARD_PHRASES, attribution trailers, and for commit
messages a lowercase subject of at most 72 characters. Soft rules (warnings): ornate nouns, "not just",
self-answered questions, three short sentences in a row closing a paragraph.
"""
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEXT_SUFFIXES = {".md", ".txt", ".html", ".css", ".ts", ".js", ".rs", ".py", ".toml", ".yml", ".yaml",
                 ".sh", ".hbs", ".svg", ".cjs", ".mjs"}
PROSE_SUFFIXES = {".md", ".txt", ".html"}
STRINGS_PREFIX = "apps/desktop/src/strings/"
ASCII_EXEMPT_PREFIXES = ("fixtures/", "assets/fonts/", "vendor/", "node_modules/", "target/", "dist/")
ASCII_EXEMPT_NAMES = {"THIRD-PARTY-NOTICES.md", "pnpm-lock.yaml", "Cargo.lock"}
VERBATIM_PREFIXES = ("docs/prompts/",)  # text other people wrote, kept as written

HARD_PHRASES = [
    "at a glance", "it's worth noting", "it is worth noting", "it bears mentioning", "here's the kicker",
    "here is the kicker", "here's where it gets interesting", "here's what most people miss",
    "the truth is simple", "the reality is simpler", "think of it as", "think of it like",
    "co-authored-by", "generated with", "generated-by", "generated by claude", "generated by ai",
    "as an ai", "in today's fast-paced", "ever-evolving", "game-changer", "game changer", "a testament to",
    "underscores the importance", "highlights the importance", "it's important to note",
    "it is important to note", "delve", "seamlessly", "cutting-edge", "unlock the", "unleash",
    "supercharge", "revolutionize", "in the realm of",
]
WARN_PHRASES = [
    "tapestry", "landscape", "not just", "importantly,", "interestingly,", "notably,", "leverage",
    "ecosystem", "paradigm", "synergy", "in summary", "in conclusion", "nuanced", "multifaceted",
    "crucial", "plays a key role", "vital role", "robust", "elevate", "streamline", "empower",
]
NAMED = {0x2014: "em dash", 0x2013: "en dash", 0x2018: "curly quote", 0x2019: "curly quote",
         0x201C: "curly quote", 0x201D: "curly quote", 0x2026: "ellipsis", 0x2022: "bullet",
         0x2192: "arrow", 0x2190: "arrow", 0x21D2: "arrow", 0x27A1: "arrow", 0x00A0: "no-break space"}
SELF_ANSWER = re.compile(r"\b(?:The|Your|Their|Our|Its|His|Her|My)\s+[\w ]{1,30}\?\s+[A-Z][\w'-]*(?:\s+[\w'-]+){0,2}\.(?:\s|$)")
TRAILER = re.compile(r"(?im)^(?:co-authored-by|signed-off-by|generated-by|generated with|reviewed-by)\b")
FENCE = re.compile(r"^\s*(```|~~~)")


def tracked():
    out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT,
                         capture_output=True, text=True, check=False)
    return [ROOT / n for n in out.stdout.splitlines()]


def rel_of(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def describe(ch: str) -> str:
    cp = ord(ch)
    return NAMED.get(cp) or unicodedata.name(ch, "non-ASCII").lower()


def lint_text(rel: str, text: str, prose: bool, ascii_rule: bool):
    """Return (hard, soft) lists of 'rel:line: message' strings."""
    hard, soft = [], []
    in_fence = False
    is_md = rel.endswith(".md")
    for n, line in enumerate(text.splitlines(), 1):
        if is_md and FENCE.match(line):
            in_fence = not in_fence
            continue
        if ascii_rule and not (is_md and in_fence):
            bad = [c for c in line if ord(c) > 0x7E and ord(c) != 0x09]
            if bad:
                hard.append(f"{rel}:{n}: {describe(bad[0])} (U+{ord(bad[0]):04X}); plain ASCII only")
        if prose and not in_fence:
            low = line.lower()
            for ph in HARD_PHRASES:
                if ph in low:
                    hard.append(f"{rel}:{n}: banned phrase '{ph}'")
            for ph in WARN_PHRASES:
                if re.search(r"(?<![\w-])" + re.escape(ph) + r"(?![\w-])", low):
                    soft.append(f"{rel}:{n}: watch the word '{ph}'")
            if SELF_ANSWER.search(line):
                soft.append(f"{rel}:{n}: self-answered question ('The X? A Y.')")
    if prose and is_md:
        soft.extend(tricolons(rel, text))
    return hard, soft


def tricolons(rel: str, text: str):
    out = []
    blocks = re.split(r"\n\s*\n", text)
    line_no = 1
    for block in blocks:
        lines = block.splitlines()
        body = " ".join(l.strip() for l in lines if l.strip() and not l.lstrip().startswith(("#", "|", "-", "*", ">", "`", "<")))
        sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", body) if s.strip()]
        if len(sentences) >= 3 and all(len(s.split()) <= 4 for s in sentences[-3:]):
            out.append(f"{rel}:{line_no}: three short sentences close this paragraph; join them")
        line_no += len(lines) + 1
    return out


def lint_file(path: Path):
    rel = rel_of(path)
    if path.suffix.lower() not in TEXT_SUFFIXES and not rel.startswith(STRINGS_PREFIX):
        return [], []
    if rel.startswith(ASCII_EXEMPT_PREFIXES + VERBATIM_PREFIXES) or path.name in ASCII_EXEMPT_NAMES:
        return [], []
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError) as e:
        return [f"{rel}: unreadable as UTF-8 ({e.__class__.__name__})"], []
    prose = path.suffix.lower() in PROSE_SUFFIXES or rel.startswith(STRINGS_PREFIX) or rel.startswith("docs/")
    return lint_text(rel, text, prose=prose, ascii_rule=True)


def lint_commit(path: Path):
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = [l for l in text.splitlines() if not l.startswith("#")]
    while lines and not lines[0].strip():
        lines.pop(0)
    hard, soft = lint_text("commit message", "\n".join(lines), prose=True, ascii_rule=True)
    subject = lines[0].strip() if lines else ""
    if not subject:
        hard.append("commit message: empty subject")
    else:
        if len(subject) > 72:
            hard.append(f"commit message: subject is {len(subject)} characters; keep it under 72")
        if not re.match(r"^[a-z0-9]", subject):
            hard.append("commit message: subject must start lowercase (area: change)")
        if subject.endswith("."):
            hard.append("commit message: no trailing period on the subject")
    if TRAILER.search("\n".join(lines)):
        hard.append("commit message: trailers are not allowed (no Co-Authored-By, Signed-off-by or attribution)")
    return hard, soft


def main(argv):
    strict = "--strict" in argv
    argv = [a for a in argv if a != "--strict"]
    if argv[:1] == ["--commit-msg"]:
        hard, soft = lint_commit(Path(argv[1]))
    else:
        paths = [Path(a) for a in argv] if argv else tracked()
        hard, soft = [], []
        for p in paths:
            if p.is_file():
                h, s = lint_file(p)
                hard.extend(h)
                soft.extend(s)
    for h in hard:
        print("FAIL " + h)
    for s in soft:
        print("warn " + s)
    print(f"{len(hard)} hard hit(s), {len(soft)} warning(s)")
    return 1 if hard or (strict and soft) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
